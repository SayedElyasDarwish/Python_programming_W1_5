print("Calculate the area of a wall.")

Feed = input("Enter the width in meters: ")
Width = float(Feed)
Width = int(Width)
Feed = input("Enter the height in meters: ")
Height = float(Feed)
Height = int(Height)


print(f"Width is {Width} m and height is {Height} m.")

Area = Width * Height
print(f"The wall will be {Area} square meters.")